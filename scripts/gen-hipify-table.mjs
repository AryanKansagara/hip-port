// Regenerates src/engine/hipifyTable.ts from the official hipify-perl script.
// The script is read as text and never executed.
//
//   curl -sLO https://raw.githubusercontent.com/ROCm/HIPIFY/amd-staging/bin/hipify-perl
//   node scripts/gen-hipify-table.mjs hipify-perl <commit> <yyyy-mm-dd>
import fs from 'node:fs'

const [file, commit = 'unknown', date = new Date().toISOString().slice(0, 10)] = process.argv.slice(2)
if (!file) { console.error('usage: gen-hipify-table.mjs <hipify-perl> [commit] [date]'); process.exit(1) }
const src = fs.readFileSync(file, 'utf8')

const section = name => {
  const a = src.indexOf(`my %${name} = (`)
  if (a < 0) throw new Error('section not found: ' + name)
  return src.slice(a, src.indexOf('\n);', a))
}
const pairs = name => [...section(name).matchAll(/^\s*'([^']+)' => \['([^']*)', '[^']*'\]/gm)].map(m => [m[1], m[2]])
const names = name => [...section(name).matchAll(/^\s*['"]([^'"]+)['"] => /gm)].map(m => m[1])
const versions = name => [...section(name).matchAll(/^\s*"([^"]+)" => "([^"]*)"/gm)].map(m => [m[1], m[2]])
const includes = () => {
  const a = src.indexOf('sub simpleIncludes {')
  return [...src.slice(a, src.indexOf('\n}', a)).matchAll(/subst\("([^"]+)", "([^"]*)", "[^"]+"\)/g)].map(m => [m[1].replaceAll('\\/', '/'), m[2].replaceAll('\\/', '/')])
}

// cuDNN rows target hipDNN, which is no longer maintained; the app maps cuDNN to MIOpen by hand.
// sockaddr_t is a cuFile helper typedef that would collide with ordinary socket code.
const skip = n => /^cudnn|^CUDNN/.test(n) || n === 'sockaddr_t'

const renames = pairs('map_core').filter(([c, h]) => c !== h && !skip(c))
const experimental = pairs('map_experimental').filter(([c, h]) => c !== h && !skip(c))
const unsupported = names('hash_HipOnlyUnsupportedFunctions').filter(n => !skip(n))
// Device functions and types without a HIP implementation. Only compiler-reserved names are
// kept: the rest (umin, saturate, mul24, ...) are too generic to flag without type information.
const deviceUnsupported = [...names('hash_UnsupportedDeviceFunctions'), ...names('hash_UnsupportedDeviceDataTypes')].filter(n => /^__|^nv_/.test(n))
const known = new Set([...renames.map(r => r[0]), ...experimental.map(r => r[0]), ...unsupported])
const deprecated = versions('deprecated_funcs').filter(([n]) => known.has(n))
const removed = versions('removed_funcs').filter(([n]) => known.has(n))
const hipVersion = src.match(/print STDERR "HIP version ([\d.]+)/)?.[1] ?? ''

const kv = (rows, sep) => rows.map(r => r.join(sep)).join(' ')
const out = `// Generated by scripts/gen-hipify-table.mjs from ROCm/HIPIFY bin/hipify-perl. Do not edit.
// Source: https://github.com/ROCm/HIPIFY (MIT licence, Copyright (c) 2015-present Advanced Micro Devices, Inc.)

export const HIPIFY_SOURCE = { repo: 'https://github.com/ROCm/HIPIFY', file: 'bin/hipify-perl', branch: 'amd-staging', commit: '${commit}', fetched: '${date}', hipVersion: '${hipVersion}' }

/** CUDA=HIP renames from %map_core. */
export const RENAMES = '${kv(renames, '=')}'

/** CUDA=HIP renames hipify only applies with -experimental. */
export const EXPERIMENTAL = '${kv(experimental, '=')}'

/** CUDA identifiers hipify reports as unsupported in HIP. */
export const UNSUPPORTED = '${unsupported.join(' ')}'

/** Device functions and types with no HIP implementation. */
export const DEVICE_UNSUPPORTED = '${deviceUnsupported.join(' ')}'

/** name:version, CUDA release that deprecated the identifier. */
export const DEPRECATED = '${kv(deprecated, ':')}'

/** name:version, CUDA release that removed the identifier. */
export const REMOVED = '${kv(removed, ':')}'

/** Header substitutions from simpleIncludes(). An empty target means hipify deletes the include. */
export const INCLUDES = '${kv(includes().filter(([c]) => c !== 'cudnn.h'), '=')}'
`
fs.writeFileSync(new URL('../src/engine/hipifyTable.ts', import.meta.url), out)
console.log({ renames: renames.length, experimental: experimental.length, unsupported: unsupported.length, deviceUnsupported: deviceUnsupported.length, deprecated: deprecated.length, removed: removed.length, bytes: out.length })

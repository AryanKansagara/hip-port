test('worklist: filters, statuses, CSV, and what survives a reload', async ({ page }) => {
  await project(page, [{ name: 'k.cu', data: CU }, { name: 'requirements.txt', data: 'pynvml\nvllm\n' }])
  await tab(page, 'Worklist')
  await expect(page.locator('table.worklist tbody tr')).toHaveCount(3)
  await page.getByLabel('Category').selectOption('dependency')
  await expect(page.locator('table.worklist tbody tr')).toHaveCount(2)
  await page.getByLabel('Severity').selectOption('high')
  await expect(page.locator('table.worklist tbody tr')).toHaveCount(1)
  await page.getByLabel('Severity').selectOption('all')
  await page.getByLabel('Category').selectOption('all')
  await page.getByLabel('Filter text').fill('warp')
  await expect(page.locator('table.worklist tbody tr')).toHaveCount(1)
  await page.getByLabel('Filter text').fill('nothing like this')
  await expect(page.getByText('No items match')).toBeVisible()
  await page.getByLabel('Filter text').fill('')
  await worklistRow(page, 'pynvml').getByRole('combobox').selectOption('wontfix')
  await expect(page.getByText('1 of 3 resolved')).toBeVisible()
  const [name, csv] = await download(page, page.getByRole('button', { name: 'Export CSV' }))
  expect(name).toBe('port-1-worklist.csv')
  expect(csv).toContain('high,dependency,requirements.txt,1,pynvml: CUDA only,NVML bindings.,Use amdsmi.,wontfix\n')
  await page.reload()
  await expect(page.getByText('1 of 3 resolved')).toBeVisible()
  await page.getByLabel('Status', { exact: true }).selectOption('resolved')
  await expect(worklistRow(page, 'pynvml').getByRole('combobox')).toHaveValue('wontfix')
})


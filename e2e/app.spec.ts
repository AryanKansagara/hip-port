test('settings: defaults reach new projects, theme persists, JSON export holds the sources', async ({ page }) => {
  await page.goto('/settings')
  await page.getByLabel('Target GPU').selectOption('gfx950')
  await page.getByLabel('Rewrite launches as hipLaunchKernelGGL').check()
  await page.getByRole('radio', { name: 'Light' }).click()
  await newProject(page)
  await expect(page.locator('html')).toHaveAttribute('data-theme-mode', 'light')
  await expect(page.getByLabel('Target GPU')).toHaveValue('gfx950')
  await importFiles(page, [{ name: 'k.cu', data: CU }], 1)
  await page.goto('/settings')
  const [name, json] = await download(page, page.getByRole('button', { name: 'Export all my data (JSON)' }))
  expect(name).toMatch(/^hip-port-export-\d{4}-\d\d-\d\d\.json$/)
  const data = JSON.parse(json)
  expect(data.projects.map((p: { name: string; ggl: boolean; dataset: unknown }) => [p.name, p.ggl, p.dataset])).toEqual([['Port 1', true, { files: [{ path: 'k.cu', text: CU }], deps: null }]])
  await page.getByRole('button', { name: 'Delete all projects' }).click()
  await page.getByRole('button', { name: 'Delete everything' }).click()
  await expect(page.locator('.toast', { hasText: 'Deleted 1 projects' })).toBeVisible()
  await page.goto('/app')
  await expect(page.getByRole('button', { name: 'Import your code' })).toBeVisible()
})

